    #[test]
    fn control_catalog_pcidss_is_complete() {
        let cat = ControlCatalog::new();
        let pci = cat.by_framework(Framework::PciDss);
        // Full PCI DSS v4.0.1 catalog: all 12 requirements with their
        // defined sub-requirements (250 controls).
        assert!(
            pci.len() >= 250,
            "PCI DSS catalog should ship the full v4.0.1 control set, got {}",
            pci.len()
        );
        // Every one of the 12 top-level requirements must be represented.
        for req in 1..=12 {
            let prefix = format!("{req}.");
            assert!(
                pci.iter().any(|c| c.id.starts_with(&prefix)),
                "PCI DSS requirement {req} has no controls in the catalog"
            );
        }
        // Spot-check representative controls spanning the standard.
        for id in [
            "1.2.1", "3.3.1.1", "4.2.1", "6.4.3", "8.4.1", "10.2.1.1", "11.4.2", "12.10.7",
        ] {
            assert!(
                cat.find(Framework::PciDss, id).is_some(),
                "PCI DSS control {id} must be in the catalog"
            );
        }
        // No duplicate control ids within the framework.
        let mut ids: Vec<&str> = pci.iter().map(|c| c.id.as_str()).collect();
        ids.sort_unstable();
        let before = ids.len();
        ids.dedup();
        assert_eq!(before, ids.len(), "duplicate PCI DSS control id present");
    }

