"use client";

import * as React from "react";
import { Download, FileText, Printer } from "lucide-react";

import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";

/** One labelled statistic in a report section. */
export interface ReportStat {
  label: string;
  value: string;
}

/** One module section of the comprehensive report. */
export interface ReportSection {
  key: string;
  title: string;
  available: boolean;
  stats: ReportStat[];
  note?: string | undefined;
}

/** The fully-aggregated report, computed server-side. */
export interface ReportModel {
  tenantName: string;
  generatedBy: string;
  generatedAtIso: string;
  kpis: {
    postureScore: number;
    totalFindings: number;
    critical: number;
    high: number;
    activeEngagements: number;
  };
  severity: { critical: number; high: number; medium: number; low: number; info: number };
  sections: ReportSection[];
  coverage: Array<{ title: string; available: boolean }>;
}

function fmtDate(iso: string): string {
  try {
    return new Date(iso).toLocaleString(undefined, {
      dateStyle: "long",
      timeStyle: "short",
    });
  } catch {
    return iso;
  }
}

/** Render the whole report as Markdown for download. */
function toMarkdown(m: ReportModel): string {
  const L: string[] = [];
  L.push(`# SentinelX Comprehensive Security Report`);
  L.push("");
  L.push(`- **Tenant:** ${m.tenantName}`);
  L.push(`- **Generated:** ${fmtDate(m.generatedAtIso)}`);
  L.push(`- **Generated by:** ${m.generatedBy}`);
  L.push("");
  L.push(`## Executive Summary`);
  L.push("");
  L.push(`| Metric | Value |`);
  L.push(`|---|---|`);
  L.push(`| Security posture score | ${m.kpis.postureScore} / 100 |`);
  L.push(`| Total findings | ${m.kpis.totalFindings} |`);
  L.push(`| Critical findings | ${m.kpis.critical} |`);
  L.push(`| High findings | ${m.kpis.high} |`);
  L.push(`| Active engagements | ${m.kpis.activeEngagements} |`);
  L.push("");
  L.push(`### Findings by severity`);
  L.push("");
  L.push(`| Critical | High | Medium | Low | Info |`);
  L.push(`|---|---|---|---|---|`);
  L.push(
    `| ${m.severity.critical} | ${m.severity.high} | ${m.severity.medium} | ${m.severity.low} | ${m.severity.info} |`,
  );
  L.push("");
  for (const s of m.sections) {
    L.push(`## ${s.title}${s.available ? "" : " _(not accessible)_"}`);
    L.push("");
    if (s.stats.length > 0) {
      L.push(`| Metric | Value |`);
      L.push(`|---|---|`);
      for (const st of s.stats) {
        L.push(`| ${st.label} | ${st.value} |`);
      }
      L.push("");
    }
    if (s.note !== undefined) {
      L.push(s.note);
      L.push("");
    }
  }
  L.push(`## Appendix — Module Coverage`);
  L.push("");
  L.push(`This report was generated from live module output. Coverage:`);
  L.push("");
  for (const c of m.coverage) {
    L.push(`- ${c.available ? "✅" : "⬜"} ${c.title}`);
  }
  L.push("");
  L.push(
    `_A module marked ⬜ was empty or not permitted for the generating account; grant the relevant \`*:read\` permission to include it._`,
  );
  return L.join("\n");
}

function download(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function sevTone(label: string): string {
  const l = label.toLowerCase();
  if (l.includes("critical")) return "text-critical";
  if (l.includes("high")) return "text-high";
  if (l.includes("medium")) return "text-medium";
  return "text-muted-foreground";
}

export function ReportingClient({ model }: { model: ReportModel }): React.JSX.Element {
  const stamp = model.generatedAtIso.slice(0, 10);

  function onMarkdown(): void {
    download(`sentinelx-report-${stamp}.md`, toMarkdown(model), "text/markdown");
  }
  function onJson(): void {
    download(`sentinelx-report-${stamp}.json`, JSON.stringify(model, null, 2), "application/json");
  }
  function onPrint(): void {
    window.print();
  }

  return (
    <div className="space-y-6">
      {/* Toolbar — hidden when printing */}
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Comprehensive Report</h1>
          <p className="text-muted-foreground">
            A single report generated from live results across every module.
          </p>
        </div>
        <div className="flex gap-2">
          <Button variant="outline" onClick={onPrint}>
            <Printer className="mr-2 h-4 w-4" aria-hidden /> Print / Save as PDF
          </Button>
          <Button variant="outline" onClick={onMarkdown}>
            <FileText className="mr-2 h-4 w-4" aria-hidden /> Markdown
          </Button>
          <Button variant="outline" onClick={onJson}>
            <Download className="mr-2 h-4 w-4" aria-hidden /> JSON
          </Button>
        </div>
      </div>

      {/* The printable report body */}
      <article className="space-y-6" id="comprehensive-report">
        <header className="border-b border-border pb-4">
          <h2 className="text-xl font-bold">SentinelX Comprehensive Security Report</h2>
          <dl className="mt-2 grid grid-cols-1 gap-x-8 gap-y-1 text-sm text-muted-foreground sm:grid-cols-3">
            <div>
              <dt className="inline font-medium">Tenant: </dt>
              <dd className="inline">{model.tenantName}</dd>
            </div>
            <div>
              <dt className="inline font-medium">Generated: </dt>
              <dd className="inline">{fmtDate(model.generatedAtIso)}</dd>
            </div>
            <div>
              <dt className="inline font-medium">By: </dt>
              <dd className="inline">{model.generatedBy}</dd>
            </div>
          </dl>
        </header>

        <section>
          <h3 className="mb-3 text-lg font-semibold">Executive Summary</h3>
          <div className="grid grid-cols-2 gap-4 md:grid-cols-5">
            <StatTile label="Posture" value={`${model.kpis.postureScore}`} suffix="/100" />
            <StatTile label="Findings" value={`${model.kpis.totalFindings}`} />
            <StatTile label="Critical" value={`${model.kpis.critical}`} tone="text-critical" />
            <StatTile label="High" value={`${model.kpis.high}`} tone="text-high" />
            <StatTile label="Active eng." value={`${model.kpis.activeEngagements}`} />
          </div>
        </section>

        <section className="grid grid-cols-1 gap-4 md:grid-cols-2">
          {model.sections.map((s) => (
            <Card key={s.key} className={s.available ? "" : "opacity-70"}>
              <CardHeader>
                <CardTitle className="flex items-center justify-between text-base">
                  <span>{s.title}</span>
                  {!s.available && (
                    <span className="text-xs font-normal text-muted-foreground">
                      not accessible
                    </span>
                  )}
                </CardTitle>
                {s.note !== undefined && <CardDescription>{s.note}</CardDescription>}
              </CardHeader>
              <CardContent>
                <dl className="space-y-1 text-sm">
                  {s.stats.map((st) => (
                    <div key={st.label} className="flex justify-between gap-4">
                      <dt className="text-muted-foreground">{st.label}</dt>
                      <dd className={`font-medium tabular-nums ${sevTone(st.label)}`}>
                        {st.value}
                      </dd>
                    </div>
                  ))}
                </dl>
              </CardContent>
            </Card>
          ))}
        </section>

        <section>
          <h3 className="mb-2 text-lg font-semibold">Appendix — Module Coverage</h3>
          <p className="mb-2 text-sm text-muted-foreground">
            Generated from live module output. Modules without data or permission are marked below.
          </p>
          <ul className="grid grid-cols-1 gap-1 text-sm sm:grid-cols-2">
            {model.coverage.map((c) => (
              <li key={c.title} className="flex items-center gap-2">
                <span aria-hidden>{c.available ? "✅" : "⬜"}</span>
                <span className={c.available ? "" : "text-muted-foreground"}>{c.title}</span>
              </li>
            ))}
          </ul>
        </section>
      </article>
    </div>
  );
}

function StatTile({
  label,
  value,
  suffix,
  tone,
}: {
  label: string;
  value: string;
  suffix?: string;
  tone?: string;
}): React.JSX.Element {
  return (
    <div className="rounded-sx border border-border bg-card px-4 py-3">
      <div className="text-xs uppercase tracking-wide text-muted-foreground">{label}</div>
      <div className={`mt-1 text-2xl font-semibold tabular-nums ${tone ?? ""}`}>
        {value}
        {suffix !== undefined && (
          <span className="ml-1 text-sm text-muted-foreground">{suffix}</span>
        )}
      </div>
    </div>
  );
}
