//! [`ControlCatalog`] — the in-process library of compliance controls.
//!
//! The catalog ships a curated subset of high-value controls for each
//! supported framework. It is constructed eagerly the first time
//! [`ControlCatalog::new`] (or [`ControlCatalog::shared`]) is called and
//! held thereafter by the caller. Lookups are O(n) but n is small
//! (well under a hundred), so we choose readability over indexing.

use std::sync::Arc;
use std::sync::OnceLock;

use crate::model::control::Control;
use crate::model::framework::Framework;

/// In-process catalog of all supported compliance controls.
///
/// Held by use-cases behind an [`Arc`] so it can be shared across
/// threads without further synchronisation.
#[derive(Debug, Clone)]
pub struct ControlCatalog {
    controls: Vec<Control>,
}

static SHARED: OnceLock<Arc<ControlCatalog>> = OnceLock::new();

impl ControlCatalog {
    /// Build a fresh catalog, populated with every shipped control.
    #[must_use]
    pub fn new() -> Self {
        let mut controls = Vec::with_capacity(512);
        controls.extend(iso27001());
        controls.extend(soc2());
        controls.extend(pcidss());
        controls.extend(hipaa());
        controls.extend(nist80053());
        controls.extend(cisaws());
        controls.extend(fedramp_moderate());
        Self { controls }
    }

    /// Return the process-wide shared [`Arc`]-held catalog, building it
    /// lazily on the first call. This is the recommended constructor
    /// for use-cases that don't need a private instance.
    #[must_use]
    pub fn shared() -> Arc<Self> {
        SHARED.get_or_init(|| Arc::new(Self::new())).clone()
    }

    /// Borrow all controls in catalog order.
    #[must_use]
    pub fn all(&self) -> &[Control] {
        &self.controls
    }

    /// Return all controls owned by `framework`.
    #[must_use]
    pub fn by_framework(&self, framework: Framework) -> Vec<&Control> {
        self.controls
            .iter()
            .filter(|c| c.framework == framework)
            .collect()
    }

    /// Look up a single control by `(framework, id)`.
    #[must_use]
    pub fn find(&self, framework: Framework, id: &str) -> Option<&Control> {
        self.controls
            .iter()
            .find(|c| c.framework == framework && c.id == id)
    }

    /// Look up a control by id across all frameworks. Returns the first
    /// hit in catalog order — IDs may collide across frameworks (PCI
    /// `1.2.1` and CIS `1.4` for example look similar) so callers that
    /// need a unique answer should pass an explicit framework.
    #[must_use]
    pub fn find_any(&self, id: &str) -> Option<&Control> {
        self.controls.iter().find(|c| c.id == id)
    }
}

impl Default for ControlCatalog {
    fn default() -> Self {
        Self::new()
    }
}

